package com.example.calcpro;

/** Готовые примеры для разделов «Уравнения» и «Примеры». Все записи проверены решателем. */
final class Catalog {
    private Catalog() {}

    static final class Item {
        final String expr;
        final String note;

        Item(String expr, String note) {
            this.expr = expr;
            this.note = note;
        }
    }

    static final class Section {
        final String title;
        final Item[] items;

        Section(String title, Item... items) {
            this.title = title;
            this.items = items;
        }
    }

    private static Item i(String expr, String note) { return new Item(expr, note); }

    static final Section[] EQUATIONS = {
        new Section("Линейные",
            i("2x + 5 = 11", "Перенос слагаемых и деление"),
            i("3(x − 4) = 2x + 1", "Раскрытие скобок"),
            i("x/3 + 2 = 5", "Дробный коэффициент"),
            i("2x + 3 = 0", "Отрицательный дробный корень")),
        new Section("Квадратные",
            i("2x² − 3x + 1 = 0", "Дискриминант, два корня"),
            i("x² − 5x + 6 = 0", "Целые корни"),
            i("x² − 2x + 1 = 0", "Один (кратный) корень"),
            i("x² + 4x + 13 = 0", "Комплексные корни")),
        new Section("Степенные и кубические",
            i("x³ − 6x² + 11x − 6 = 0", "Три корня, разложение на множители"),
            i("x⁴ − 5x² + 4 = 0", "Биквадратное уравнение"),
            i("x⁴ = 16", "Корни четвёртой степени"),
            i("x¹⁰ = 1", "Корни из единицы")),
        new Section("Системы",
            i("x + y = 5; 2x − y = 1", "Два уравнения, два неизвестных"),
            i("x + 2y = 4; 3x − y = 5", "Определители (правило Крамера)")),
        new Section("Иррациональные",
            i("√(x + 4) = 3", "Возведение в квадрат и проверка"),
            i("√(2x + 1) = x − 1", "Проверка посторонних корней")),
        new Section("Тригонометрические",
            i("sin(x) = 0,5", "Корни на отрезке [−10; 10]"),
            i("cos(x) = 0", "Серия корней"),
            i("tan(x) = 1", "Периодические решения")),
    };

    static final Section[] EXAMPLES = {
        new Section("Арифметика",
            i("(2 + 3) · 4 ÷ 5 − 2^3", "Порядок действий"),
            i("2^10 − 3!", "Степень и факториал"),
            i("240 · 15%", "Проценты"),
            i("7/3 + 5/6", "Дроби точно: 19/6"),
            i("10! / 8!", "Факториалы")),
        new Section("Корни и степени",
            i("√(144) + ∛(27)", "Квадратный и кубический корень"),
            i("2² + 3³", "Степени")),
        new Section("Тригонометрия и логарифмы",
            i("sin(π/6) + cos(π/3)", "Табличные значения"),
            i("ln(e^2)", "Натуральный логарифм"),
            i("log(1000) + lg(100)", "Десятичный логарифм"),
            i("abs(-7) + 3", "Модуль |x|")),
        new Section("Графики функций",
            i("sin(x)", "График с осями и сеткой"),
            i("x² − 2x", "Парабола"),
            i("√x", "Корень на графике"),
            i("∛(x)", "Кубический корень")),
    };
}
